export function useAppLanguage(section) {
  const [language, setLanguage] = useState(() => getLanguage());

  useEffect(() => {
    const handleLanguageChange = (event) => setLanguage(event.detail || getLanguage());
    const handleStorage = () => setLanguage(getLanguage());

    window.addEventListener("languageChange", handleLanguageChange);
    window.addEventListener("storage", handleStorage);

    return () => {
      window.removeEventListener("languageChange", handleLanguageChange);
      window.removeEventListener("storage", handleStorage);
    };
  }, []);

  const isRTL = language === "ar";

  useEffect(() => {
    document.documentElement.dir = isRTL ? "rtl" : "ltr";
    document.documentElement.lang = language;
  }, [isRTL, language]);

  const t = (key) => translations[language]?.[section]?.[key] || translations.en[section]?.[key] || "";

  return { language, t, isRTL };
}